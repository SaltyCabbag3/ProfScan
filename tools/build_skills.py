"""Writes RecipeSkill.lua: every profession recipe's skill-up thresholds, from the game's
SkillLineAbility table (via wago.tools, cached in tools/.db2cache like build_recipes.py).

    python build_skills.py [build]      (default build 1.60.1.70888)

  yellow = TrivialSkillLineRankLow   skill where the recipe turns yellow (skill-ups no longer certain)
  grey   = TrivialSkillLineRankHigh  skill where it turns grey (no more skill-ups)
  green is halfway between (the game's rule). Orange starts at the skill needed to learn
  the recipe, which the game's table doesn't hold for most recipes (MinSkillLineRank is 1);
  ProfScan takes it from RecipeData.lua (recipe.skill). A recipe whose yellow is below its
  learn level is yellow from the start.
"""
import sys
from pathlib import Path

from build_recipes import SKILL_LINES, game_tables

HERE = Path(__file__).resolve().parent
EXTRA_LINES = {"Fishing": 356, "Herbalism": 182, "Skinning": 393}


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else "1.60.1.70888"
    game = game_tables(build, ["SkillLineAbility"])
    lines = {**SKILL_LINES, **EXTRA_LINES}
    by_line = {v: k for k, v in lines.items()}
    rows = {}
    for r in game["SkillLineAbility"]:
        line = int(r["SkillLine"])
        if line not in by_line:
            continue
        low, high = int(r["TrivialSkillLineRankLow"]), int(r["TrivialSkillLineRankHigh"])
        if high <= 0:
            continue
        spell = int(r["Spell"])
        rows[spell] = (low, high, by_line[line])
    out = [
        f"-- Generated by tools/build_skills.py from the game's SkillLineAbility table (build {build},",
        "-- via wago.tools). Do not edit by hand; run the script again instead.",
        "local _, ns = ...",
        "",
        "-- [recipe spell ID] = { yellow, grey }: the skill where the recipe turns yellow and grey",
        "-- (green is halfway between). See Recipes.lua, ns:SkillThresholds.",
        "ns.RECIPE_SKILL = {",
    ]
    for spell in sorted(rows):
        low, high, _ = rows[spell]
        out.append(f"  [{spell}] = {{ {low}, {high} }},")
    out.append("}")
    path = HERE.parent / "RecipeSkill.lua"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    counts = {}
    for _, _, prof in rows.values():
        counts[prof] = counts.get(prof, 0) + 1
    print(f"wrote {path} with {len(rows)} recipes: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))


if __name__ == "__main__":
    main()
